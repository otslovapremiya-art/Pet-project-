// Состояние игры. Единственное место, где хранится правда о том,
// что происходит в игре. Число на экране — только отражение этого объекта.
const состояние = {
    ресурс: 0,

    // Сколько прибавляется само, без нажатий, каждую секунду.
    // В начале игры ноль: пока не куплено ни одного улучшения,
    // само ничего не растёт, первые очки набиваются кнопкой.
    приростВСекунду: 0,

    // Сколько очков стоит следующее улучшение. После каждой покупки удваивается.
    ценаУлучшения: 10,

    // Сколько улучшений уже куплено. На экране не показывается,
    // но пригодится, когда появится сохранение прогресса.
    купленоУлучшений: 0
};


// Находим элементы страницы один раз при запуске и запоминаем их,
// чтобы не искать заново при каждом нажатии.
const элементЧисла = document.getElementById("число");
const элементКнопки = document.getElementById("кнопка");
const элементКнопкиПокупки = document.getElementById("кнопкаПокупки");


// Показывает текущее состояние на экране.
// Вызывается после каждого изменения состояния — и только так.
function показатьСостояние() {
    элементЧисла.textContent = состояние.ресурс;

    // Цена пишется прямо внутри кнопки, чтобы её было видно, не отводя глаз.
    элементКнопкиПокупки.textContent = "Купить улучшение — " + состояние.ценаУлучшения;

    // Когда очков не хватает, кнопка выключается: на неё нельзя нажать,
    // и по её виду сразу понятно, что покупка пока недоступна.
    элементКнопкиПокупки.disabled = состояние.ресурс < состояние.ценаУлучшения;
}


// Что происходит при нажатии кнопки: ресурс увеличивается на единицу,
// после чего экран перерисовывается.
function нажатьКнопку() {
    состояние.ресурс = состояние.ресурс + 1;
    показатьСостояние();
}


// Что происходит каждую секунду само: ресурс увеличивается на прирост,
// после чего экран перерисовывается. Правило то же, что и у кнопки:
// изменили состояние — сразу показали.
function тик() {
    состояние.ресурс = состояние.ресурс + состояние.приростВСекунду;
    показатьСостояние();
}


// Что происходит при покупке улучшения.
function купитьУлучшение() {
    // Если очков меньше цены — не делаем ничего. Кнопка в этот момент
    // и так выключена, но проверка здесь остаётся: она главная,
    // а выключенная кнопка — только подсказка глазу.
    if (состояние.ресурс < состояние.ценаУлучшения) {
        return;
    }

    состояние.ресурс = состояние.ресурс - состояние.ценаУлучшения;
    состояние.приростВСекунду = состояние.приростВСекунду + 1;
    состояние.купленоУлучшений = состояние.купленоУлучшений + 1;
    состояние.ценаУлучшения = состояние.ценаУлучшения * 2;

    показатьСостояние();
}


// Связываем кнопки с действиями.
элементКнопки.addEventListener("click", нажатьКнопку);
элементКнопкиПокупки.addEventListener("click", купитьУлучшение);


// Просим браузер вызывать функцию "тик" каждую секунду.
// 1000 — это миллисекунды, то есть одна секунда.
// Замечание: когда вкладка свёрнута, браузер сам замедляет такие
// таймеры ради экономии батареи. Это его поведение, не наша ошибка.
setInterval(тик, 1000);


// Первый показ при запуске страницы, чтобы на экране было 0, а не пусто.
показатьСостояние();
